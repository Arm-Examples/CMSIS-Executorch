#!/usr/bin/env python3
"""Generate firmware/src/params_gen.h from firmware/model/params.json.

    python tools/gen_params_h.py                      # default paths
    python tools/gen_params_h.py --check              # exit 1 if the header is stale

params.json is the exact copy of Reproduce_Baselines' preprocess_params.json
(release v0.5-distill; v0.3-distill, the previous model, has the same schema).
The header carries everything the board pipeline needs:
the band-pass SOS, the 9 per-subject EA matrices, the input scales and the
int8 quantisation of the model input. Values are written with 17 significant
digits (round-trip exact for float64); the firmware decides the precision it
computes in (see firmware/src/preprocess.h).

Deterministic output (no timestamps), so re-running it on the same params.json
gives a byte-identical header.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_IN = ROOT / "firmware" / "model" / "params.json"
DEFAULT_OUT = ROOT / "firmware" / "src" / "params_gen.h"


def lit(v: float) -> str:
    """A C double literal that round-trips to the same float64."""
    s = repr(float(v))
    if "e" not in s and "." not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s


def matrix(rows, indent: str) -> str:
    lines = []
    for row in rows:
        lines.append(indent + "{" + ", ".join(lit(x) for x in row) + "},")
    return "\n".join(lines)


def generate(params_path: Path) -> str:
    raw = params_path.read_bytes()
    p = json.loads(raw)
    if p.get("version") != "v2":
        raise SystemExit(f"{params_path}: version {p.get('version')!r}, expected 'v2'")

    n_ch = int(p["n_channels"])
    n_samples = int(p["n_samples"])
    sos = p["sos"]
    win = p["window"]
    dec = p["decimation"]
    eas = p["ea_matrices"]
    order = p["channel_order"]

    if n_ch != 22 or n_samples != 256:
        raise SystemExit(f"unexpected shape {n_ch}x{n_samples}")
    if len(sos) != 4 or any(len(r) != 6 for r in sos):
        raise SystemExit("sos must be 4 x 6")
    if any(abs(r[3] - 1.0) > 0 for r in sos):
        raise SystemExit("sos a0 must be 1.0")
    if int(dec["factor"]) != 2 or int(dec["phase"]) != 0:
        raise SystemExit(f"unsupported decimation {dec}")
    if int(win["length"]) != n_samples:
        raise SystemExit("window length != n_samples")
    if float(p["fs"]) != 250.0 or float(p["fs_model"]) != 125.0:
        raise SystemExit("expected fs 250 Hz, fs_model 125 Hz")
    if p.get("reference") != "common_average_22":
        raise SystemExit(f"unsupported reference {p.get('reference')!r}")
    subjects = sorted(int(k) for k in eas)
    if subjects != list(range(1, 10)):
        raise SystemExit(f"ea_matrices keys {subjects}, expected 1..9")
    for k, m in eas.items():
        if len(m) != n_ch or any(len(r) != n_ch for r in m):
            raise SystemExit(f"ea_matrices[{k}] is not {n_ch}x{n_ch}")
    if len(order) != n_ch:
        raise SystemExit("channel_order length")

    sha = hashlib.sha256(raw).hexdigest()
    out = []
    w = out.append
    w("// Generated by tools/gen_params_h.py from firmware/model/params.json -- do not edit.")
    w(f"// params.json sha256 {sha}")
    w(f"// version {p['version']}, export subject A{int(p['subject']):02d}, "
      f"student {p.get('student', {}).get('name', '?')}")
    w("// Pipeline (Reproduce_Baselines/docs/v2_handoff.md): CAR -> SOS band-pass at 250 Hz ->")
    w("// keep even samples -> window [cue_125 + WINDOW_START, + N_SAMPLES) -> EA[subject] ->")
    w("// / INPUT_SCALE -> rint(/ INPUT_QUANT_SCALE) + INPUT_ZERO_POINT, clamp to int8.")
    w("#ifndef PARAMS_GEN_H_")
    w("#define PARAMS_GEN_H_")
    w("")
    w("#define PARAMS_VERSION \"v2\"")
    w(f"#define PARAMS_SHA256 \"{sha}\"")
    w(f"#define PARAMS_EXPORT_SUBJECT {int(p['subject'])}")
    w(f"#define N_CH {n_ch}")
    w(f"#define N_SAMPLES {n_samples}")
    w(f"#define WINDOW_START {int(win['start_samples_after_cue_125hz'])}")
    w(f"#define DECIMATION {int(dec['factor'])}")
    w(f"#define DECIMATION_PHASE {int(dec['phase'])}")
    w(f"#define FS_HZ {int(float(p['fs']))}")
    w(f"#define FS_MODEL_HZ {int(float(p['fs_model']))}")
    w(f"#define N_SOS {len(sos)}")
    w(f"#define N_SUBJECTS {len(subjects)}")
    w(f"#define INPUT_SCALE {lit(p['input_scale'])}")
    w(f"#define INPUT_QUANT_SCALE {lit(p['input_quant_scale'])}")
    w(f"#define INPUT_ZERO_POINT ({int(p['input_zero_point'])})")
    w("")
    w("// Second-order sections, rows {b0, b1, b2, a0 (= 1), a1, a2}, applied in order (DF2-T).")
    w("static const double SOS[N_SOS][6] = {")
    w(matrix(sos, "    "))
    w("};")
    w("")
    w("// Euclidean-alignment matrices, EA[s - 1] for 2a subject s (A01..A09): x_ea = EA @ x.")
    w("static const double EA[N_SUBJECTS][N_CH][N_CH] = {")
    for s in subjects:
        w(f"    {{  // A{s:02d}")
        w(matrix(eas[str(s)], "        "))
        w("    },")
    w("};")
    w("")
    w("// UART channel order (index = position in the int16 data frame).")
    w("static const char *const CHANNEL_ORDER[N_CH] = {")
    w("    " + ", ".join(f"\"{c}\"" for c in order) + ",")
    w("};")
    w("")
    w("#endif  // PARAMS_GEN_H_")
    w("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--params", type=Path, default=DEFAULT_IN)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="only compare; exit 1 if --out differs")
    args = ap.parse_args()

    text = generate(args.params)
    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is stale; run tools/gen_params_h.py", file=sys.stderr)
            return 1
        print(f"{args.out} up to date")
        return 0
    args.out.write_text(text)
    print(f"wrote {args.out} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
